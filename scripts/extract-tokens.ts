/**
 * Generates src/design/tokens/generated/* from the datamined Discord token package.
 *
 *   bun scripts/extract-tokens.ts <path-to-discord-mobile-datamining>
 *
 * The datamined files are decompiled but evaluable data modules. They are run
 * inside an empty `node:vm` context with their imports replaced by stubs.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import vm from 'node:vm'

const dataminingRoot = process.argv[2]
if (!dataminingRoot) {
    console.error(
        'usage: bun scripts/extract-tokens.ts <path-to-discord-mobile-datamining>',
    )
    process.exit(1)
}

const tokensDir = join(
    resolve(dataminingRoot),
    'discord_common/js/packages/tokens',
)
const outDir = resolve(import.meta.dir, '../src/design/tokens/generated')

// Discord's theme ids. ASH is the default dark theme, DARK is the legacy darker one.
const Themes = {
    ASH: 'dark',
    LIGHT: 'light',
    ONYX: 'midnight',
    DARK: 'darker',
} as const
type ThemeId = (typeof Themes)[keyof typeof Themes]
const themeIds = Object.values(Themes) as ThemeId[]
// ASH and ONYX fall back to DARK for tokens they do not define (ThemeExtends).
const themeFallback: Partial<Record<ThemeId, ThemeId>> = {
    dark: 'darker',
    midnight: 'darker',
}

function load(relativePath: string): Record<string, any> {
    const source = readFileSync(join(tokensDir, relativePath), 'utf8')
        .replace(/^import .*$/gm, '')
        .replace(/^export const (\w+) =/gm, 'exports.$1 =')
        // The decompiler turns `for (const x of experiments)` into a loop that never
        // terminates; restore the original shape.
        .replace(
            /const iter = enabledExperiments\[Symbol\.iterator\]\(\);/g,
            '',
        )
        .replace(
            /while \(iter !== undefined\) \{/g,
            'for (const experiment of enabledExperiments) {',
        )
        .replace(/const nextResult = iter\.next\(\);/g, '')
        .replace(/\bnextResult\b/g, 'experiment')
        .replace(/=== iter\.next\(\)/g, '=== experiment')
        .replace(/iter\.return\(\);/g, '')
    const exports: Record<string, any> = {}
    vm.runInNewContext(source, {
        exports,
        ThemeTypes: { _private: { Themes } },
        size: { fileFinishedImporting() {} },
    })
    return exports
}

function withOpacity(hex: string, opacity: number): string {
    // Some raw colors (OPACITY_*) already carry an alpha channel; `opacity` restates it.
    const rgb = hex.slice(0, 7)
    if (opacity >= 1) return rgb
    const alpha = Math.round(opacity * 255)
        .toString(16)
        .padStart(2, '0')
    return `${rgb}${alpha}`
}

function emit(file: string, body: string) {
    writeFileSync(
        join(outDir, file),
        `// Generated by scripts/extract-tokens.ts. Do not edit.\n${body}`,
    )
}

const json = (value: unknown) => JSON.stringify(value, null, 2)

mkdirSync(outDir, { recursive: true })

// Raw colors
const rawColors: Record<string, string> = load(
    'colors/generated/raw-color-definitions.tsx',
)._private.RawColors
emit('rawColors.ts', `export const rawColors = ${json(rawColors)} as const;\n`)

// Semantic colors, resolved per theme
type SemanticDefinition = Partial<
    Record<ThemeId, { raw: string; opacity: number }>
>
const semantic: Record<string, SemanticDefinition> = load(
    'colors/generated/native/generated-definitions.tsx',
)._private.SemanticColors

// Experiments Isocord treats as permanently enabled, most specific first: a resolver
// that gives several of them a value takes the first match, so `-floating` must precede
// the `mobile-visual-refresh` it builds on.
const ENABLED_EXPERIMENTS = [
    'mobile-visual-refresh-floating',
    'refresh-fast-follow-avatars',
    'mobile-visual-refresh',
    'mana-type-consolidation',
]

const colorExperiments: Record<
    string,
    Record<string, SemanticDefinition>
> = load('colors/generated/native/experiment-definitions.tsx')._private
    .SemanticColorExperiments
for (const [name, byExperiment] of Object.entries(colorExperiments)) {
    // Least specific first, so the most specific override is merged last and wins.
    for (const experiment of [...ENABLED_EXPERIMENTS].reverse()) {
        if (byExperiment[experiment])
            semantic[name] = { ...semantic[name], ...byExperiment[experiment] }
    }
}

const colorsByTheme = Object.fromEntries(
    themeIds.map(id => [id, {} as Record<string, string>]),
)
for (const [name, definition] of Object.entries(semantic)) {
    for (const id of themeIds) {
        const fallback = themeFallback[id]
        const entry =
            definition[id] ?? (fallback ? definition[fallback] : undefined)
        if (!entry)
            throw new Error(
                `Semantic color ${name} has no value for theme ${id}`,
            )
        const hex = rawColors[entry.raw]
        if (!hex)
            throw new Error(
                `Semantic color ${name} references unknown raw color ${entry.raw}`,
            )
        colorsByTheme[id]![name] = withOpacity(hex, entry.opacity)
    }
}
emit(
    'semanticColors.ts',
    `export type ThemeId = ${themeIds.map(id => `'${id}'`).join(' | ')};\n` +
        `export type SemanticColor = ${Object.keys(semantic)
            .map(name => `'${name}'`)
            .join(' | ')};\n` +
        `export const semanticColors: Record<ThemeId, Record<SemanticColor, string>> = ${json(colorsByTheme)};\n`,
)

// Typography
interface TextVariant {
    name: string
    fontStack: 'primary' | 'headline' | 'nitro' | 'code'
    uppercase: boolean
    italic: boolean
    weight: number
    size: number
    lineHeight: number
}
const weightNames: Record<number, string> = {
    400: 'Normal',
    500: 'Medium',
    600: 'Semibold',
    700: 'Bold',
    800: 'ExtraBold',
}

function fontFamily(variant: TextVariant): string {
    const italic = variant.italic ? 'Italic' : ''
    switch (variant.fontStack) {
        case 'primary':
            return `ggsans-${weightNames[variant.weight]}${italic}`
        case 'code':
            return `ggmono-${variant.weight >= 700 ? 'Bold' : 'Normal'}`
        case 'headline':
            return `ABCGintoNord-ExtraBold${italic}`
        case 'nitro':
            return `ABCGintoDiscordNord-Bold${italic}`
    }
}

const variants: TextVariant[] = load(
    'typography/generated/TextVariants.tsx',
).TextVariantsFlat
const textStyles = Object.fromEntries(
    variants.map(variant => [
        variant.name,
        {
            fontFamily: fontFamily(variant),
            fontSize: variant.size,
            lineHeight: variant.lineHeight,
            ...(variant.uppercase ? { textTransform: 'uppercase' } : {}),
        },
    ]),
)

// The client remaps every Text, Heading and username variant through the enabled
// experiments' tables (useTypographyVariantRemap). Bake that in: a remapped name carries
// the style of its target, so app code keeps using the original names.
type VariantRemap = { text: Map<string, string>; heading: Map<string, string> }
const typographyRemaps: Map<string, VariantRemap> = load(
    'typography/generated/TypographyVariantRemap.tsx',
).TYPOGRAPHY_EXPERIMENT_REMAPS
const activeRemaps = [...typographyRemaps].filter(([experiment]) =>
    ENABLED_EXPERIMENTS.includes(experiment),
)
for (const [experiment, remap] of activeRemaps) {
    // Heading would consult this table before `text`; it is empty today.
    if (remap.heading.size > 0)
        throw new Error(`Typography remap ${experiment} has heading entries`)
}
let remappedVariants = 0
const textVariants = Object.fromEntries(
    Object.entries(textStyles).map(([name, style]) => {
        const target = activeRemaps
            .map(([, remap]) => remap.text.get(name))
            .find(value => value != null)
        if (target == null) return [name, style]
        if (!textStyles[target])
            throw new Error(
                `Typography remap ${name} targets unknown variant ${target}`,
            )
        remappedVariants++
        return [name, textStyles[target]]
    }),
)
emit(
    'typography.ts',
    `export const textVariants = ${json(textVariants)} as const;\nexport type TextVariant = keyof typeof textVariants;\n`,
)

// Component tokens ("modules"), resolved for each chat density
const densities = ['compact', 'default', 'cozy'] as const
type Resolver = {
    resolve: (context: {
        density: string
        enabledExperiments: string[]
    }) => unknown
}
const moduleDefinitions: Record<string, Record<string, Resolver>> = load(
    'modules/generated/generated-definitions.tsx',
)._private.Modules
// The decompiled resolvers return on the first loop iteration, and some of them return
// their fallback for experiments they never mention. Give each resolver only the enabled
// experiments it names (still in priority order) so unrelated ones cannot affect it.
const experimentsFor = (token: Resolver) => {
    const source = String(token.resolve)
    return ENABLED_EXPERIMENTS.filter(experiment =>
        source.includes(`"${experiment}"`),
    )
}
const modulesByDensity = Object.fromEntries(
    densities.map(density => [
        density,
        Object.fromEntries(
            Object.entries(moduleDefinitions).map(([group, tokens]) => [
                group,
                Object.fromEntries(
                    Object.entries(tokens).map(([name, token]) => [
                        name,
                        token.resolve({
                            density,
                            enabledExperiments: experimentsFor(token),
                        }),
                    ]),
                ),
            ]),
        ),
    ]),
)
emit(
    'modules.ts',
    `export type Density = ${densities.map(density => `'${density}'`).join(' | ')};\n` +
        `export const modules = ${json(modulesByDensity)} as const;\n`,
)

// Radii, spacing, shadows
const radii = load('radii/generated/generated-definitions.tsx').Radius
emit('radii.ts', `export const radii = ${json(radii)} as const;\n`)

const layout = load('layout/generated/generated-definitions.tsx')
const layoutValues: Record<string, unknown> = Object.values(layout).find(
    value => value && typeof value === 'object' && 'SPACE_16' in value,
) as Record<string, unknown>
const space: Record<string, number> = {}
for (const [name, value] of Object.entries(layoutValues)) {
    // Only numeric SPACE_n tokens exist on native; the named ones are CSS variables.
    if (name.startsWith('SPACE_') && typeof value === 'number')
        space[`PX_${name.slice('SPACE_'.length)}`] = value
}
emit('space.ts', `export const space = ${json(space)} as const;\n`)

type ShadowDefinition = Partial<Record<ThemeId, { boxShadow: string }>>
const shadows: Record<string, ShadowDefinition> = load(
    'shadows/generated/shared/generated-definitions.tsx',
)._private.Shadows
const shadowsByTheme = Object.fromEntries(
    themeIds.map(id => [id, {} as Record<string, string>]),
)
for (const [name, definition] of Object.entries(shadows)) {
    for (const id of themeIds) {
        const fallback = themeFallback[id]
        const entry =
            definition[id] ?? (fallback ? definition[fallback] : undefined)
        if (!entry)
            throw new Error(`Shadow ${name} has no value for theme ${id}`)
        // React Native's boxShadow accepts the CSS string, minus the `none` hue keyword.
        shadowsByTheme[id]![name] = entry.boxShadow.replaceAll(
            'hsl(none ',
            'hsl(0 ',
        )
    }
}
emit(
    'shadows.ts',
    `export type ShadowName = ${Object.keys(shadows)
        .map(name => `'${name}'`)
        .join(' | ')};\n` +
        `export const shadows: Record<string, Record<ShadowName, string>> = ${json(shadowsByTheme)};\n`,
)

console.log(
    `tokens: ${Object.keys(rawColors).length} raw colors, ${Object.keys(semantic).length} semantic colors, ` +
        `${variants.length} text variants (${remappedVariants} remapped), ${Object.keys(shadows).length} shadows -> ${outDir}`,
)
