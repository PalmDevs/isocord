/**
 * Extracts Discord's Mana icon PNGs from the xxhdpi resource split and
 * generates the icon registry.
 *
 *   bun scripts/extract-icons.ts <path-to-discord-mobile-datamining> <path-to-res.apk>
 */
import {
    mkdirSync,
    readdirSync,
    renameSync,
    rmSync,
    writeFileSync,
} from 'node:fs'
import { join, resolve } from 'node:path'

const [dataminingRoot, resApk] = process.argv.slice(2)
if (!dataminingRoot || !resApk) {
    console.error(
        'usage: bun scripts/extract-icons.ts <path-to-discord-mobile-datamining> <path-to-res.apk>',
    )
    process.exit(1)
}

const PREFIX = 'design_components_icon_native_redesign_generated_images_'
const iconsDir = resolve(import.meta.dir, '../src/design/icons')
const imagesDir = join(iconsDir, 'images')

// Resource names are lowercased; the datamined component files give the real casing.
const componentDir = join(
    resolve(dataminingRoot),
    'discord_app/design/components/Icon/native/redesign/generated',
)
const namesByLowercase = new Map(
    readdirSync(componentDir)
        .filter(file => file.endsWith('.tsx'))
        .map(file => file.slice(0, -'.tsx'.length))
        .map(name => [name.toLowerCase(), name]),
)

rmSync(imagesDir, { recursive: true, force: true })
mkdirSync(imagesDir, { recursive: true })
const unzip = Bun.spawnSync([
    'unzip',
    '-joq',
    resolve(resApk),
    `res/drawable-xxhdpi-v4/${PREFIX}*.png`,
    '-d',
    imagesDir,
])
if (unzip.exitCode !== 0) throw new Error(unzip.stderr.toString())

// Resource names are lowercase with no word breaks, so unmatched ones are
// only capitalized (e.g. `foobaricon` -> `FoobarIcon`).
// Word breaks for icons newer than the datamine.
const OVERRIDES: Record<string, string> = {
    emojislightlysmilingfaceicon: 'EmojiSlightlySmilingFaceIcon',
}
const nameFor = (lowercase: string) =>
    namesByLowercase.get(lowercase) ??
    OVERRIDES[lowercase] ??
    lowercase.charAt(0).toUpperCase() +
        lowercase.slice(1).replace(/icon$/, 'Icon')

const names: string[] = []
// Two-layer icons ship as `<name>primary` and `<name>secondary` images.
const duotone = new Map<string, Set<string>>()
for (const file of readdirSync(imagesDir)) {
    const lowercase = file.slice(PREFIX.length, -'.png'.length)
    const layer = /^(.*icon)(primary|secondary)$/.exec(lowercase)
    if (layer) {
        const layeredName = nameFor(layer[1]!)
        renameSync(
            join(imagesDir, file),
            join(imagesDir, `${layeredName}.${layer[2]}@3x.png`),
        )
        duotone.set(
            layeredName,
            (duotone.get(layeredName) ?? new Set()).add(layer[2]!),
        )
    } else {
        const name = nameFor(lowercase)
        renameSync(join(imagesDir, file), join(imagesDir, `${name}@3x.png`))
        names.push(name)
    }
}
names.sort()
const duotoneNames = [...duotone]
    .filter(([, layers]) => layers.size === 2)
    .map(([name]) => name)
    .sort()

writeFileSync(
    join(iconsDir, 'generated.ts'),
    `// Generated by scripts/extract-icons.ts. Do not edit.\nexport const iconSources = {\n${names
        .map(name => `  ${name}: () => require('./images/${name}.png'),`)
        .join('\n')}\n} as const;\n\n` +
        `/** Icons drawn as a tinted primary layer over an optional secondary layer. */\nexport const duotoneIconSources = {\n${duotoneNames
            .map(
                name =>
                    `  ${name}: () => ({ primary: require('./images/${name}.primary.png'), secondary: require('./images/${name}.secondary.png') }),`,
            )
            .join('\n')}\n} as const;\n`,
)
console.log(
    `icons: ${names.length} single, ${duotoneNames.length} duotone, of ${namesByLowercase.size} components -> ${imagesDir}`,
)
